// Helper to generate items
const generateCategoryItems = (categoryName, roomName, imagesList, titles, basePrice) => {
  return imagesList.map((imgUrl, idx) => {
    const title = titles[idx] || `${categoryName} Atelier Piece ${idx + 1}`;
    const price = basePrice + (idx * 6000) - (idx % 3 === 0 ? 4000 : 0);
    const mrp = Math.round(price * 1.18);
    const discount = Math.round(((mrp - price) / mrp) * 100);
    const rating = (4.8 + ((idx % 3) * 0.08)).toFixed(2);
    const reviewsCount = 18 + (idx * 3);

    return {
      id: `${categoryName.toLowerCase().replace(/[^a-z0-9]/g, '')}-${idx + 1}`,
      name: title,
      subtitle: `Handcrafted ${categoryName.toLowerCase()} crafted from seasoned natural timbers and refined architectural finishes`,
      category: categoryName,
      room: roomName,
      collection: idx % 2 === 0 ? 'The Contemporary Edit' : 'The Luxe Edit',
      price: price,
      mrp: mrp,
      discount: discount,
      rating: parseFloat(rating),
      reviewsCount: reviewsCount,
      badge: idx === 0 ? 'Bestseller' : (idx === 1 ? 'Signature' : (idx === 2 ? 'New Release' : '')),
      isNew: idx % 3 === 0,
      isBestseller: idx < 2,
      emi: `From ₹${Math.round(price / 12).toLocaleString('en-IN')}/mo with 0% EMI`,
      image: `${imgUrl}?auto=format&fit=crop&w=1200&q=80`,
      gallery: [
        `${imgUrl}?auto=format&fit=crop&w=1200&q=80`,
        `${imagesList[(idx + 1) % imagesList.length]}?auto=format&fit=crop&w=1200&q=80`
      ],
      finishes: [
        { name: 'Oatmeal Bouclé / Natural Teak', color: '#E8E1D5' },
        { name: 'Smoked Walnut / Charcoal', color: '#3A3938' },
        { name: 'Terracotta Velvet / Brass', color: '#9E5B42' }
      ],
      materials: 'FSC-Certified Kiln-Dried Hardwood Frame, High-Resilience Foam Core, Premium Fabric & Metal Inlays',
      dimensions: 'Custom architectural proportions suited for modern open living',
      warranty: '10-Year Structural Frame Warranty & 3-Year Guarantee',
      story: `Conceived as an architectural centerpiece, this ${categoryName.toLowerCase()} celebrates pure material truth, ergonomic comfort and refined joinery.`,
      features: [
        'Reinforced solid kiln-dried timber construction with mortise & tenon joinery',
        'Hydrophobic nano-sealant stain-resistant treatment',
        'Engineered for decades of daily family comfort'
      ]
    };
  });
};

